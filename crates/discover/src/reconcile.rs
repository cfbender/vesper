//! Plans file changes that make a machine's generated services match what its
//! containers declare, without touching anything a person wrote.
//!
//! Each generated service is one file, `machines/<m>/services/<s>.yaml`,
//! whose header carries a marker with the SHA-256 of the YAML below it. A file
//! is managed only while that hash matches: once a person (or the Vesper
//! editor) changes the YAML, discovery never updates or removes it again.
//! The configuration labels of Vesper's own container become
//! [`LABELS_FILE`], owned the same way.

use crate::labels::Discovered;
use chrono::{DateTime, SecondsFormat, Utc};
use sha2::{Digest, Sha256};
use std::collections::{BTreeMap, BTreeSet};
use std::time::Duration;
use vesper_core::config::{
    export_partial, export_service, validate, FileChange, LoadedConfig, LABELS_FILE,
};
use vesper_core::{Config, SecretRef, Service};

const MARKER: &str = "# vesper-discover: ";

/// One machine's scan: what its containers declare, or why Docker could not
/// be read.
pub struct Source {
    pub machine: String,
    pub scan: Result<Discovered, String>,
    pub allowed_secrets: Vec<SecretRef>,
}

#[derive(Debug, Default)]
pub struct Report {
    /// Applied (or, in a dry run, planned) changes.
    pub changes: Vec<String>,
    /// Situations that need no action but explain why labels were ignored.
    pub warnings: Vec<String>,
    /// Situations where discovery could not do what the labels ask.
    pub errors: Vec<String>,
}

pub struct Plan {
    pub changes: Vec<FileChange>,
    pub config: Config,
    pub report: Report,
}

#[derive(Debug, PartialEq)]
enum Ownership {
    Managed {
        missing_since: Option<DateTime<Utc>>,
    },
    Edited,
    Foreign,
}

fn digest(text: &str) -> String {
    Sha256::digest(text.as_bytes())
        .iter()
        .map(|b| format!("{b:02x}"))
        .collect()
}

pub fn render(machine: &str, service: &Service, missing_since: Option<DateTime<Utc>>) -> String {
    let body = export_service(service).expect("a service always serializes");
    let mut out = format!(
        "# Generated by `vesper discover` from Docker labels on machine {machine}.\n\
         # Change the containers' vesper.* labels instead of this file. Once this\n\
         # YAML is edited, discovery leaves the file alone; delete it to regenerate.\n\
         {MARKER}sha256={}",
        digest(&body)
    );
    if let Some(t) = missing_since {
        out.push_str(" missing-since=");
        out.push_str(&t.to_rfc3339_opts(SecondsFormat::Secs, true));
    }
    out.push('\n');
    out.push_str(&body);
    out
}

fn render_labels(value: &serde_json::Value) -> String {
    let body = export_partial(value);
    format!(
        "# Generated by `vesper discover` from the vesper.* configuration labels of\n\
         # the container Vesper runs in. Change those labels instead of this file.\n\
         # Values set in any other configuration file take precedence over these.\n\
         # Once this YAML is edited, discovery leaves the file alone; delete it to\n\
         # regenerate.\n\
         {MARKER}sha256={}\n{body}",
        digest(&body)
    )
}

fn ownership(content: &str) -> Ownership {
    let mut offset = 0;
    for line in content.split_inclusive('\n') {
        if !line.starts_with('#') {
            break;
        }
        offset += line.len();
        let Some(fields) = line.strip_prefix(MARKER) else {
            continue;
        };
        let mut hash = None;
        let mut missing_since = None;
        for field in fields.split_whitespace() {
            match field.split_once('=') {
                Some(("sha256", h)) => hash = Some(h),
                Some(("missing-since", t)) => {
                    missing_since = DateTime::parse_from_rfc3339(t)
                        .ok()
                        .map(|t| t.with_timezone(&Utc))
                }
                _ => {}
            }
        }
        return if hash == Some(digest(&content[offset..]).as_str()) {
            Ownership::Managed { missing_since }
        } else {
            Ownership::Edited
        };
    }
    Ownership::Foreign
}

/// A change to the configuration that must validate before it is written.
struct Candidate {
    machine: String,
    service: String,
    path: String,
    /// `None` removes the service.
    next: Option<(Service, String)>,
    note: String,
}

impl Candidate {
    fn apply(&self, config: &mut Config) {
        // Writing a service file creates its machine's directory if needed.
        let services = &mut config
            .machines
            .entry(self.machine.clone())
            .or_default()
            .services;
        match &self.next {
            Some((service, _)) => {
                services.insert(self.service.clone(), service.clone());
            }
            None => {
                services.remove(&self.service);
            }
        }
    }
}

fn time(t: DateTime<Utc>) -> String {
    t.to_rfc3339_opts(SecondsFormat::Secs, true)
}

fn secrets_allowed(service: &Service, allowed: &[SecretRef]) -> bool {
    service.checks.values().all(|check| {
        check
            .headers
            .values()
            .chain(check.token.iter())
            .all(|s| allowed.contains(s))
    })
}

/// Plans the change to [`LABELS_FILE`] that the Vesper container's
/// configuration labels ask for, if it was among the scanned containers.
/// Returns the configuration with that change applied.
fn plan_labels(
    loaded: &LoadedConfig,
    files: &BTreeMap<String, String>,
    preview: &dyn Fn(&[FileChange]) -> anyhow::Result<LoadedConfig>,
    sources: &[Source],
    changes: &mut Vec<FileChange>,
    report: &mut Report,
) -> Config {
    let declared = sources
        .iter()
        .find_map(|s| s.scan.as_ref().ok()?.config.as_ref());
    let value = match declared {
        None => return loaded.config.clone(),
        Some(Err(e)) => {
            report.errors.push(format!(
                "Vesper's own labels: {e}; {LABELS_FILE} was left unchanged"
            ));
            return loaded.config.clone();
        }
        Some(Ok(value)) => value,
    };
    let current = files.get(LABELS_FILE);
    let empty = value.as_object().is_some_and(|o| o.is_empty());
    let change = match current.map(|c| ownership(c)) {
        Some(Ownership::Edited) if !empty => {
            report.warnings.push(format!("{LABELS_FILE} was edited by hand, so Vesper's own configuration labels are ignored; delete the file to regenerate it"));
            None
        }
        Some(Ownership::Foreign) if !empty => {
            report.warnings.push(format!("{LABELS_FILE} was written by hand, so Vesper's own configuration labels are ignored"));
            None
        }
        Some(Ownership::Edited | Ownership::Foreign) => None,
        Some(Ownership::Managed { .. }) if empty => Some(FileChange::Delete {
            path: LABELS_FILE.into(),
        }),
        _ if empty => None,
        _ => {
            let content = render_labels(value);
            (current != Some(&content)).then(|| FileChange::Write {
                path: LABELS_FILE.into(),
                content,
            })
        }
    };
    let Some(change) = change else {
        return loaded.config.clone();
    };
    match preview(std::slice::from_ref(&change)) {
        Ok(next) => {
            report.changes.push(format!(
                "{} {LABELS_FILE} from Vesper's own labels",
                match (&change, current) {
                    (FileChange::Delete { .. }, _) => "removed",
                    (_, Some(_)) => "updated",
                    (_, None) => "created",
                }
            ));
            changes.push(change);
            next.config
        }
        Err(e) => {
            // Validation lists its problems below a heading line.
            let e = format!("{e:#}");
            let skip = usize::from(e.lines().count() > 1);
            let lines: Vec<&str> = e
                .lines()
                .skip(skip)
                .map(|l| l.trim_start_matches("- "))
                .collect();
            report.errors.push(format!(
                "Vesper's own labels: {}; {LABELS_FILE} was left unchanged",
                lines.join("; ")
            ));
            loaded.config.clone()
        }
    }
}

/// Plans one reconciliation of `sources` against the current configuration.
/// `preview` returns the configuration that whole-file changes would
/// produce. `remove_after` is how long a generated service must go
/// undeclared before its file is removed; `None` never removes it.
pub fn plan(
    loaded: &LoadedConfig,
    files: &BTreeMap<String, String>,
    preview: &dyn Fn(&[FileChange]) -> anyhow::Result<LoadedConfig>,
    sources: &[Source],
    now: DateTime<Utc>,
    remove_after: Option<Duration>,
) -> Plan {
    let mut report = Report::default();
    let mut changes = Vec::new();
    let mut candidates = Vec::new();
    let mut config = plan_labels(loaded, files, preview, sources, &mut changes, &mut report);
    // Machines written inline in a file, which discovery cannot add to.
    let machines_inline = loaded.sources.iter().find_map(|(path, file)| {
        (path.starts_with("machines/")
            && path.matches('/').count() == 1
            && !file.starts_with("machines/")
            && file != LABELS_FILE)
            .then_some(file.as_str())
    });
    let no_machine = vesper_core::Machine::default();
    'sources: for source in sources {
        let m = source.machine.as_str();
        let defined_in = loaded
            .sources
            .get(&format!("machines/{m}"))
            .map(String::as_str);
        match defined_in {
            None | Some(LABELS_FILE) => {
                if let Some(file) = machines_inline {
                    report.errors.push(format!(
                        "{m}: no machine directory, and machines are defined in {file}; create machines/{m}/_index.yaml after moving every machine into its own directory"
                    ));
                    continue;
                }
            }
            Some(d)
                if d == format!("machines/{m}/_index.yaml") || d == format!("machines/{m}/") => {}
            Some(d) => {
                report.errors.push(format!(
                    "{m}: discovery writes one file per service, but this machine is defined in {d}; move its fields to machines/{m}/_index.yaml and its services to machines/{m}/services/"
                ));
                continue;
            }
        }
        let machine = loaded.config.machines.get(m).unwrap_or(&no_machine);
        let dir = format!("machines/{m}/services/");
        let mut managed = BTreeMap::new();
        let mut hand_written = BTreeMap::new();
        for sid in machine.services.keys() {
            let defined_in = loaded
                .sources
                .get(&format!("machines/{m}/services/{sid}"))
                .cloned()
                .unwrap_or_default();
            if !defined_in.starts_with(&dir) {
                report.errors.push(format!(
                    "{m}: services are defined in {defined_in}; discovery needs them in separate files under {dir}"
                ));
                continue 'sources;
            }
            let path = format!("{dir}{sid}.yaml");
            let owner = if defined_in == path {
                ownership(&files[&path])
            } else {
                Ownership::Foreign
            };
            match owner {
                Ownership::Managed { missing_since } => {
                    managed.insert(sid.as_str(), (path, missing_since));
                }
                other => {
                    hand_written.insert(sid.as_str(), (defined_in, other));
                }
            }
        }
        // Revoking a grant must not leave a previously generated check using
        // that secret. Pause it even if Docker is unavailable. Hand-written
        // or detached files remain the administrator's responsibility.
        let mut revoked = BTreeSet::new();
        for (sid, (path, missing_since)) in &managed {
            let service = &machine.services[*sid];
            if !service.paused && !secrets_allowed(service, &source.allowed_secrets) {
                let mut paused = service.clone();
                paused.paused = true;
                candidates.push(Candidate {
                    machine: m.into(),
                    service: sid.to_string(),
                    path: path.clone(),
                    next: Some((paused.clone(), render(m, &paused, *missing_since))),
                    note: format!(
                        "paused {m}/{sid}: a secret is no longer granted to this machine"
                    ),
                });
                revoked.insert(*sid);
            }
        }
        let found = match &source.scan {
            Ok(found) => found,
            Err(e) => {
                report.errors.push(format!(
                    "{m}: cannot read Docker ({e}); left its discovered services unchanged ({}) except any revoked secret grants",
                    managed.len()
                ));
                continue;
            }
        };
        for problem in &found.problems {
            report.errors.push(format!("{m}: {problem}"));
        }
        for warning in &found.warnings {
            report.warnings.push(format!("{m}: {warning}"));
        }
        for (sid, reason) in &found.broken {
            report.errors.push(format!(
                "{m}/{sid}: {reason}; {}",
                if managed.contains_key(sid.as_str()) {
                    "kept its current definition"
                } else {
                    "not created"
                }
            ));
        }
        let mut blocked = !found.problems.is_empty() || !found.broken.is_empty();
        for (sid, service) in &found.services {
            if let Some((defined_in, owner)) = hand_written.get(sid.as_str()) {
                report.warnings.push(if *owner == Ownership::Edited {
                    format!("{m}/{sid}: {defined_in} was edited by hand, so its Docker labels are ignored; delete the file to regenerate it")
                } else {
                    format!("{m}/{sid}: defined by hand in {defined_in}, so its Docker labels are ignored")
                });
                continue;
            }
            if !secrets_allowed(service, &source.allowed_secrets) {
                report.errors.push(format!("{m}/{sid}: secret reference not granted by VESPER_DISCOVER_ALLOWED_SECRETS; labels were not applied"));
                blocked = true;
                continue;
            }
            if revoked.contains(sid.as_str()) {
                // Apply the pause first. Safe replacement labels can resume
                // the service on the next scan.
                continue;
            }
            let path = format!("{dir}{sid}.yaml");
            let content = render(m, service, None);
            let note = match managed.get(sid.as_str()) {
                Some(_) if files[&path] == content => continue,
                Some((_, Some(_))) => "restored",
                Some((_, None)) => "updated",
                None => "created",
            };
            candidates.push(Candidate {
                machine: m.into(),
                service: sid.clone(),
                path,
                next: Some((service.clone(), content)),
                note: format!("{note} {m}/{sid}"),
            });
        }
        for (sid, (path, missing_since)) in &managed {
            if found.services.contains_key(*sid)
                || found.broken.contains_key(*sid)
                || revoked.contains(*sid)
            {
                continue;
            }
            if blocked {
                continue;
            }
            let since = missing_since.unwrap_or(now);
            let due = remove_after.map(|d| since + d);
            if due.is_some_and(|due| due <= now) {
                candidates.push(Candidate {
                    machine: m.into(),
                    service: sid.to_string(),
                    path: path.clone(),
                    next: None,
                    note: format!(
                        "removed {m}/{sid}: no container has declared it since {}",
                        time(since)
                    ),
                });
            } else if missing_since.is_none() {
                changes.push(FileChange::Write {
                    path: path.clone(),
                    content: render(m, &machine.services[*sid], Some(now)),
                });
                report.changes.push(match due {
                    Some(due) => format!(
                        "{m}/{sid}: no container declares it; it stays monitored and will be removed at {} unless a container declares it again",
                        time(due)
                    ),
                    None => format!(
                        "{m}/{sid}: no container declares it; it stays monitored (removal is disabled)"
                    ),
                });
            }
        }
    }
    // Accept every change that keeps the configuration valid. Repeat so that
    // services depending on each other in one scan are accepted together.
    loop {
        let before = candidates.len();
        candidates.retain(|c| {
            let mut trial = config.clone();
            c.apply(&mut trial);
            if validate(&trial).is_err() {
                return true;
            }
            config = trial;
            changes.push(match &c.next {
                Some((_, content)) => FileChange::Write {
                    path: c.path.clone(),
                    content: content.clone(),
                },
                None => FileChange::Delete {
                    path: c.path.clone(),
                },
            });
            report.changes.push(format!("{} ({})", c.note, c.path));
            false
        });
        if candidates.len() == before {
            break;
        }
    }
    for c in candidates {
        let mut trial = config.clone();
        c.apply(&mut trial);
        let error = validate(&trial).expect_err("rejected above").to_string();
        let prefix = format!("machines.{}.services.{}", c.machine, c.service);
        let mut lines: Vec<&str> = error
            .lines()
            .filter(|l| l.contains(&format!("{prefix}.")) || l.contains(&format!("{prefix}:")))
            .collect();
        if lines.is_empty() {
            lines = error.lines().skip(1).collect();
        }
        report.errors.push(format!(
            "{}/{}: {}; {}",
            c.machine,
            c.service,
            lines
                .iter()
                .map(|l| l.trim_start_matches("- "))
                .collect::<Vec<_>>()
                .join("; "),
            match (&c.next, files.contains_key(&c.path)) {
                (None, _) => "kept",
                (Some(_), true) => "kept its current definition",
                (Some(_), false) => "not created",
            }
        ));
    }
    Plan {
        changes,
        config,
        report,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn ownership_follows_the_body_hash() {
        let service = Service {
            name: "Web".into(),
            ..Service::default()
        };
        let t = DateTime::parse_from_rfc3339("2026-11-10T12:00:00Z")
            .unwrap()
            .with_timezone(&Utc);
        assert_eq!(
            ownership(&render("m", &service, None)),
            Ownership::Managed {
                missing_since: None
            }
        );
        assert_eq!(
            ownership(&render("m", &service, Some(t))),
            Ownership::Managed {
                missing_since: Some(t)
            }
        );
        let edited = render("m", &service, None).replace("name: Web", "name: Web # mine");
        assert_eq!(ownership(&edited), Ownership::Edited);
        assert_eq!(ownership("# a comment\nname: Web\n"), Ownership::Foreign);
        assert_eq!(
            ownership(&format!("name: Web\n{MARKER}sha256=00\n")),
            Ownership::Foreign,
            "a marker below the YAML does not count"
        );
    }
}
